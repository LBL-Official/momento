//! Machine-readable feature dictionary.

use serde::Serialize;

use crate::availability::FeatureLayer;

#[derive(Clone, Debug, Serialize)]
pub struct FeatureDoc {
    pub feature_name: String,
    pub layer: String,
    pub datatype: String,
    pub unit: String,
    pub definition: String,
    pub source: String,
    pub source_timestamp_rule: String,
    pub availability: String,
    pub formula: String,
    pub lookback: String,
    pub allowed_null_reason: String,
    pub leakage_status: String,
    pub version: String,
}

#[allow(clippy::too_many_arguments)]
fn doc(
    name: &str,
    layer: FeatureLayer,
    datatype: &str,
    unit: &str,
    definition: &str,
    source: &str,
    rule: &str,
    avail: &str,
    formula: &str,
    lookback: &str,
    nulls: &str,
    leak: &str,
) -> FeatureDoc {
    FeatureDoc {
        feature_name: name.into(),
        layer: layer.as_str().into(),
        datatype: datatype.into(),
        unit: unit.into(),
        definition: definition.into(),
        source: source.into(),
        source_timestamp_rule: rule.into(),
        availability: avail.into(),
        formula: formula.into(),
        lookback: lookback.into(),
        allowed_null_reason: nulls.into(),
        leakage_status: leak.into(),
        version: crate::versions::FEATURE_SCHEMA_VERSION.into(),
    }
}

